#!/usr/bin/env python3
"""Draws the About page "Global Delivery" map: a dot-matrix world (real coastlines from global-land-mask),
amber glow around each Exterprise location, pins, labels and arcs from the Dallas HQ.
Writes the SVG straight into about.html between <!-- map --> markers.

    pip install global-land-mask && python3 tools/map.py
"""
import math, pathlib, re
from global_land_mask import globe

ROOT = pathlib.Path(__file__).resolve().parent.parent
W, H = 1200, 453                 # viewBox; equirectangular
LON0, LAT0, LAT1 = -188.5, 78, -58  # map centred between Dallas and India so the phone crop keeps every pin
STEP = 1.6                        # degrees between dots

def xy(lat, lon):
    return (lon - LON0) / 360 * W, (LAT0 - lat) / (LAT0 - LAT1) * H

SITES = [  # name, role, lat, lon, label dx, dy, anchor
    ("Dallas, TX", "Headquarters", 32.78, -96.80, -14, -22, "end"),
    ("San Pedro Sula", "Nearshore delivery center", 15.50, -88.03, -14, 30, "end"),
    ("Chennai", "Main offshore delivery center", 13.08, 80.27, 16, -24, "start"),
    ("Coimbatore", "Offshore delivery center", 11.02, 76.96, 16, 34, "start"),
]

# phone labels sit on the inner side of each pin so the cropped map never cuts them
MOB = {"Dallas, TX": (16, -14, "start"), "San Pedro Sula": (18, 28, "start"), "Chennai": (-18, -22, "end"), "Coimbatore": (-18, 38, "end")}

def dots():
    base, hot = [], {1: [], 2: [], 3: []}
    lat = LAT0
    while lat > LAT1:
        lon = LON0 + STEP / 2
        while lon < LON0 + 360:
            L = ((lon + 180) % 360) - 180
            if globe.is_land(lat, L):
                x, y = xy(lat, lon)
                d = min(math.hypot(lat - s[2], (L - s[3]) * math.cos(math.radians(lat))) for s in SITES)
                band = 3 if d < 4 else 2 if d < 8 else 1 if d < 13 else 0
                (hot[band] if band else base).append((x, y))
            lon += STEP
        lat -= STEP
    return base, hot

def path(points):
    out, py, px = [], None, None
    for x, y in points:
        if py is not None and abs(y - py) < .01:
            out.append(f"m{x - px:.1f} 0h0")
        else:
            out.append(f"M{x:.1f} {y:.1f}h0")
        px, py = x, y
    return "".join(out).replace(".0 ", " ").replace(".0h", "h")

def arc(a, b, lift):
    (x1, y1), (x2, y2) = a, b
    cx, cy = (x1 + x2) / 2, min(y1, y2) - lift
    return f"M{x1:.1f} {y1:.1f}Q{cx:.1f} {cy:.1f} {x2:.1f} {y2:.1f}"

def build():
    base, hot = dots()
    P = {s[0]: xy(s[2], s[3]) for s in SITES}
    hq = P["Dallas, TX"]
    arcs = [(arc(hq, P["San Pedro Sula"], 46), 2.6), (arc(hq, P["Chennai"], 230), 5.2), (arc(hq, P["Coimbatore"], 200), 5.8)]
    g = []
    g.append(f'<path class="wm-land" d="{path(base)}"/>')
    for band, op in ((1, .38), (2, .62), (3, .95)):
        g.append(f'<path class="wm-hot" stroke-opacity="{op}" d="{path(hot[band])}"/>')
    for i, (d, dur) in enumerate(arcs):
        g.append(f'<path class="wm-arc" d="{d}" pathLength="1"/><path class="wm-flow" d="{d}" pathLength="1" style="--dl:{i * .7}s"/>'
                 f'<circle class="wm-pkt" r="3.2"><animateMotion dur="{dur}s" begin="{i * .7}s" repeatCount="indefinite" path="{d}"/></circle>')
    for name, role, lat, lon, dx, dy, anchor in SITES:
        x, y = P[name]
        hqc = " wm-hq" if role == "Headquarters" else ""
        g.append(f'<g class="wm-site{hqc}" transform="translate({x:.1f} {y:.1f})"><circle class="wm-ring" r="7"/><circle class="wm-ring r2" r="7"/>'
                 f'<circle class="wm-dot" r="5.5"/>'
                 f'<text class="wm-l" text-anchor="{anchor}" x="{dx}" y="{dy}"><tspan class="wm-n">{name}</tspan>'
                 f'<tspan class="wm-r" x="{dx}" dy="19">{role}</tspan></text>'
                 f'<text class="wm-l wm-lm" text-anchor="{MOB[name][2]}" x="{MOB[name][0]}" y="{MOB[name][1]}">{name.split(",")[0]}</text></g>')
    return (f'<figure class="xp-map wmap"><svg aria-labelledby="wm-t" class="wm" preserveAspectRatio="xMidYMid slice" role="img" viewBox="0 0 {W} {H}">'
            f'<title id="wm-t">World map of Exterprise locations: headquarters in Dallas, Texas; nearshore delivery center in San Pedro Sula, Honduras; '
            f'offshore delivery centers in Chennai and Coimbatore, India</title>{"".join(g)}</svg>'
            f'<span aria-hidden="true" class="xp-map-glow"></span></figure>')

def main():
    f = ROOT / "about.html"; s = f.read_text(encoding="utf-8")
    new = "<!-- map: generated by tools/map.py -->" + build() + "<!-- /map -->"
    if "<!-- map: generated" in s:
        s = re.sub(r"<!-- map: generated.*?<!-- /map -->", lambda m: new, s, flags=re.S)
    else:
        s, n = re.subn(r'<figure class="xp-map">.*?</figure>', lambda m: new, s, count=1, flags=re.S); assert n
    f.write_text(s, encoding="utf-8")
    print("map written,", len(new) // 1024, "KB")

if __name__ == "__main__":
    main()
